"""Age and sex by source and class (split-v3 cohort and KAUH holdout) → research/DEMOGRAPHICS.md.

Sources of demographics:
- ICBHI: the challenge's ``demographic_info.txt`` (126 patients: ID, age, sex, adult BMI, child
  weight, child height). The official site's TLS certificate had expired, so it was fetched from
  the Kaggle mirror (``vbookshelf/respiratory-sound-database``) into
  ``backend/dataset/ICBHI_demographic_info.txt`` (gitignored).
- KAUH: age and sex from the file name (``BP12_Asthma,E W,P L R,24,M.wav``). This covers both the
  KAUH recordings and the Kaggle clips traced to KAUH patients (IDs 900,000 + n).
- Kaggle remainder: no demographics exist.

    python research/tools/demographics.py
"""

from __future__ import annotations

import csv
import hashlib
import re
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "backend"
DEMO = BACKEND / "dataset/ICBHI_demographic_info.txt"
CLASSES = ("asthma", "bronchial", "copd", "healthy", "pneumonia")


def icbhi_demographics() -> dict[int, tuple[float | None, str | None]]:
    out = {}
    for line in DEMO.read_text().splitlines():
        parts = line.split()
        if len(parts) == 6:
            age = None if parts[1] == "NA" else float(parts[1])
            out[int(parts[0])] = (age, None if parts[2] == "NA" else parts[2])
    return out


def kauh_demographics() -> dict[int, tuple[float | None, str | None]]:
    out = {}
    for path in (BACKEND / "dataset/KAUH/audio").glob("*.wav"):
        match = re.match(r"^[BDE]P(\d+)_.*,(\d+),([MF])\.wav$", path.name)
        if match:
            out[900_000 + int(match.group(1))] = (float(match.group(2)), match.group(3))
    return out


def summarize(pairs: list[tuple[float | None, str | None]]) -> str:
    ages = [a for a, _ in pairs if a is not None]
    female = sum(s == "F" for _, s in pairs)
    known_sex = sum(s is not None for _, s in pairs)
    if not pairs:
        return "—"
    age = f"{statistics.median(ages):.0f} [{min(ages):.0f}–{max(ages):.0f}]" if ages else "n/a"
    return f"n={len(pairs)}; age {age}; F {female}/{known_sex}" if known_sex else f"n={len(pairs)}; age {age}"


def main() -> None:
    icbhi, kauh = icbhi_demographics(), kauh_demographics()
    groups: dict[tuple[str, str], dict[int, tuple]] = defaultdict(dict)
    with (BACKEND / "artifacts/latest/split_manifest.csv").open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            pid = int(row["patient_id"])
            if row["source"] == "icbhi":
                source, demo = "ICBHI", icbhi.get(int(Path(row["path"]).name.split("_")[0]), (None, None))
            elif pid >= 900_000:
                source, demo = ("KAUH (cohort)" if row["source"] == "kauh" else "Kaggle clips from KAUH"), kauh.get(pid, (None, None))
            else:
                source, demo = "Kaggle remainder", None
            groups[(source, row["disease"])][pid] = demo
    with (BACKEND / "data/kauh_external_holdout_manifest.csv").open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            groups[("KAUH (holdout)", row["label"])][int(row["patient_id"])] = kauh.get(int(row["patient_id"]), (None, None))

    sources = ("ICBHI", "Kaggle clips from KAUH", "KAUH (cohort)", "KAUH (holdout)", "Kaggle remainder")
    lines = [
        "# Demographics by source and class",
        "",
        "Generated by `research/tools/demographics.py`. Patients of the split-v3 cohort plus the KAUH",
        "holdout; age as median [range] in years, then females / patients with known sex.",
        f"ICBHI demographics: `demographic_info.txt` (Kaggle mirror; SHA-256 `{hashlib.sha256(DEMO.read_bytes()).hexdigest()[:16]}…`).",
        "KAUH: age and sex from the file names. Kaggle remainder: no demographics exist.",
        "",
        "| Source | " + " | ".join(CLASSES) + " | out of label |",
        "|---|" + "---|" * 6,
    ]
    for source in sources:
        cells = []
        for label in (*CLASSES, "out_of_label"):
            members = groups.get((source, label), {})
            if not members:
                cells.append("—")
            elif source == "Kaggle remainder":
                cells.append(f"n={len(members)}; unknown")
            else:
                cells.append(summarize(list(members.values())))
        lines.append(f"| {source} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "**Reading:** age differs sharply between sources and classes, so an age effect cannot be",
        "separated from the source effect with this data. ICBHI includes children (mainly",
        "bronchiolitis/URTI). Any source-confounding claim must allow for population differences",
        "(novelty review R3/R5).",
    ]
    (ROOT / "research/DEMOGRAPHICS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[7:14]))


if __name__ == "__main__":
    main()
