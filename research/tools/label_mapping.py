"""Generate research/LABEL_MAPPING.md: how each dataset's labels become the five project classes.

Reads the mapping constants the pipeline actually uses (``reorganize_icbhi.ICBHI_TO_5CLASS``,
``kauh.LABELS``), the authentic ICBHI diagnoses, the Kaggle class folders, the KAUH file names and
the split-v3 cohort audit, so the table cannot drift from what was trained.

    python research/tools/label_mapping.py
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "backend"
sys.path.insert(0, str(BACKEND))
from kauh import LABELS, parse_name  # noqa: E402
from reorganize_icbhi import ICBHI_TO_5CLASS  # noqa: E402

KAGGLE = BACKEND / "dataset/Asthma_Detection_V2/Asthma Detection Dataset Version 2/Asthma Detection Dataset Version 2"


def main() -> None:
    with (BACKEND / "dataset/patient_diagnosis_authentic.csv").open(newline="", encoding="utf-8") as handle:
        icbhi = Counter(row["disease"] for row in csv.DictReader(handle))
    kaggle = {d.name: sum(1 for _ in d.glob("*.wav")) for d in sorted(KAGGLE.iterdir()) if d.is_dir()}
    kauh_files = sorted((BACKEND / "dataset/KAUH/audio").glob("*.wav"))
    kauh_patients: dict[str, set[int]] = defaultdict(set)
    for path in kauh_files:
        rec = parse_name(path)
        kauh_patients[rec.diagnosis].add(rec.patient)
    audit = json.loads((BACKEND / "artifacts/latest/dataset_audit.json").read_text())["per_source"]
    sides = {}
    for name in ("kauh_cohort_manifest.csv", "kauh_external_holdout_manifest.csv"):
        with (BACKEND / "data" / name).open(newline="", encoding="utf-8") as handle:
            sides[name] = Counter(row["label"] for row in csv.DictReader(handle))

    lines = [
        "# Label mapping: source labels → the five project classes",
        "",
        "Generated by `research/tools/label_mapping.py` from the constants the pipeline uses",
        "(`reorganize_icbhi.ICBHI_TO_5CLASS`, `kauh.LABELS`), the authentic ICBHI diagnoses, the Kaggle class",
        "folders, the KAUH file names and the split-v3 cohort audit. Do not edit by hand.",
        "",
        "## 1. Where each label comes from",
        "",
        "| Dataset | Field the label is read from | Unit the label applies to |",
        "|---|---|---|",
        "| ICBHI 2017 | `patient_diagnosis_authentic.csv` → `disease` (one diagnosis per patient) | patient |",
        "| Kaggle Asthma Detection V2 | class **folder name** (`asthma`, `Bronchial`, `copd`, `healthy`, `pneumonia`), lower-cased | clip (no patient field) |",
        "| KAUH (Fraiwan et al.) | diagnosis segment of the **file name** (`BP12_Asthma,E W,P L R,24,M.wav` → `asthma`) | recording; one diagnosis per patient |",
        "",
        "## 2. Mapping",
        "",
        "| Project class | ICBHI diagnoses (patients) | Kaggle folder (clips, before exclusions) | KAUH diagnosis (patients) |",
        "|---|---|---|---|",
    ]
    for project in ("asthma", "bronchial", "copd", "healthy", "pneumonia"):
        icbhi_part = ", ".join(f"{k} ({icbhi[k]})" for k, v in ICBHI_TO_5CLASS.items() if v == project and k in icbhi) or "—"
        kaggle_part = ", ".join(f"`{k}` ({n})" for k, n in kaggle.items() if k.lower() == project) or "—"
        kauh_part = ", ".join(f"`{k}` ({len(kauh_patients[k])})" for k, v in LABELS.items() if v == project and k in kauh_patients) or "—"
        lines.append(f"| **{project}** | {icbhi_part} | {kaggle_part} | {kauh_part} |")
    unmapped = sorted(k for k in kauh_patients if k not in LABELS)
    lines += [
        f"| *out of label* | — | — | {', '.join(f'`{k}` ({len(kauh_patients[k])})' for k in unmapped)} |",
        "",
        "ICBHI diagnoses not listed under a class are excluded upstream. KAUH out-of-label patients are",
        "used only as out-of-label external audio (X5), never for training.",
        "",
        "## 3. Counts in the split-v3 cohort (recordings, after overlap exclusion and deduplication)",
        "",
        "| Source | " + " | ".join(("asthma", "bronchial", "copd", "healthy", "pneumonia")) + " | patients |",
        "|---|" + "---:|" * 6,
    ]
    for source, v in audit.items():
        counts = v["recording_label_counts"]
        lines.append(f"| {source} | " + " | ".join(str(counts.get(c, 0)) for c in ("asthma", "bronchial", "copd", "healthy", "pneumonia"))
                     + f" | {v['patients']} |")
    lines += [
        "",
        "KAUH recordings by side (labels as mapped):",
        f"- in training cohort (`data/kauh_cohort_manifest.csv`): {dict(sides['kauh_cohort_manifest.csv'])}",
        f"- external holdout (`data/kauh_external_holdout_manifest.csv`): {dict(sides['kauh_external_holdout_manifest.csv'])}",
        "",
        "## 4. Definition mismatches a reader must know",
        "",
        "- **\"bronchial\" is a grouping, not a diagnosis.**",
        "  - In ICBHI it pools URTI, bronchiectasis, bronchiolitis and LRTI, four different conditions.",
        "  - Kaggle's `Bronchial` folder has no documented definition.",
        "  - KAUH `BRON` is not defined in its source; read as bronchitis, bronchiectasis or a bronchial sound.",
        "  - Claims about \"bronchial\" are therefore claims about a heterogeneous group.",
        "- **\"healthy\" differs by source.** ICBHI \"Healthy\" are healthy volunteers (mostly recorded on the",
        "  Meditron). KAUH `N` is the diagnosis \"normal\", and the same files also carry `N` in the",
        "  sound-type segment (normal breath sound). Kaggle `healthy` is undocumented.",
        "- **Asthma comes almost only from Kaggle and KAUH.** ICBHI has one asthma patient.",
        "- **COPD comes almost only from ICBHI** (793 of 805 recordings); KAUH adds 4 patients.",
        "- **KAUH multi-diagnosis patients** (`heart failure + copd`, `asthma and lung fibrosis`, …) are",
        "  out of label in the KAUH cohort and holdout (`kauh.LABELS` matches the full string). Kaggle clips",
        "  cut from such a patient keep Kaggle's folder label. `main.assign_kauh_patient_ids` only checks",
        "  that it equals the patient's *first* listed diagnosis (`KauhRecording.primary_label`), so an",
        "  `asthma and lung fibrosis` patient's clips train as asthma.",
        "- **Conflicting duplicates:** three byte-identical KAUH file pairs carry different diagnoses",
        "  (patients 100/101 and 76/77: normal vs asthma). See `backend/data/kauh_internal_duplicates.csv`",
        "  and C-21.",
        "- **Unit mismatch:** the ICBHI and KAUH labels belong to patients; the Kaggle labels belong to",
        "  clips with no patient identity (only 316 clips were traced back to real KAUH patients).",
    ]
    (ROOT / "research/LABEL_MAPPING.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:40]))


if __name__ == "__main__":
    main()
